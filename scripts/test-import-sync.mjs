import assert from 'node:assert/strict';
import {importVerification,sourceChanges,syncVerification} from '../public/verification-import.js';
import {normalize,consolidateRecords,replacementPreview,mergeSources} from '../public/import-model.js';
const source={'Pondasi':'Ada, sebagian rapuh, tidak kokoh','Kolom':'Tidak ada, seluruhnya rapuh','Dinding':'Tembok kondisi sebagian besar retak, papan atau bahan lain yang kurang kokoh dan tidak kedap air','Luas Rumah (m�)':'36','Hasil Verifikasi':'Direkomendasikan','Status':'Selesai Verifikasi','Kecukupan Luas Ruang':'2'};
const mapped=importVerification(source);
assert.equal(mapped.criteria['condition-structure-0'],'B');
assert.equal(mapped.criteria['condition-structure-2'],'C');
assert.equal(mapped.criteria['condition-wall'],'B');
assert.equal(mapped.criteria['field-house-area'],'36');
assert.equal(mapped.criteria.recommendation,undefined);
assert.equal(mapped.criteria['condition-area'],undefined);
assert.equal(mapped.unmapped.length,1);
const swadaya=importVerification({'Material Eksisting (ringkasan)':'Kayu: 10 batang; Jendela: 2 buah','Dana Keswadayaan (ringkasan)':'Tabungan: Rp1.250.000'});
assert.equal(swadaya.criteria['material-used-0-value'],'10 batang');
assert.equal(swadaya.criteria['material-used-4-available'],'Ada');
assert.equal(swadaya.criteria['money-0-value'],'1250000');
assert.equal(importVerification({'Akses Air Minum':'Ya'}).criteria['condition-water'],'A');
assert.equal(importVerification({'Akses Air Minum':'Tidak'}).criteria['condition-water'],'C');
assert.equal(importVerification({'Pencahayaan':'Kurang terang sehingga kurang jelas untuk membaca dengan normal, memerlukan pencahayaan buatan pada siang hari'}).criteria['condition-light'],'B');
assert.deepEqual(importVerification({...source,Status:'Proses Verifikasi','Hasil Verifikasi':'Tidak Direkomendasikan'}),mapped);
assert.deepEqual(syncVerification({a:'B'},{a:'A'},{a:'A'}),{criteria:{a:'B'},conflicts:[]});
assert.deepEqual(syncVerification({a:'C'},{a:'B'},{a:'A'}),{criteria:{a:'B'},conflicts:['a']});
assert.deepEqual(syncVerification({},{a:'A'},{a:'A'}),{criteria:{},conflicts:[]});
assert.deepEqual(sourceChanges({a:'B',b:'2'},{a:'C',b:'2',c:'baru'}),{a:{before:'B',after:'C'}});
const base={...normalize('bahv',{}),id:'62010003',year:'2026',name:'Contoh',nik:'1234567890123456',region:'Wilayah',district:'Kecamatan',village:'Desa',verification:'Direkomendasikan',ba:'BA 1'};
const consolidated=consolidateRecords('bahv',[base,{...base,ba:'BA 2'}]);
assert.equal(consolidated.records.length,1);assert.equal(consolidated.records[0].ba,'BA 1 ; BA 2');assert.equal(consolidated.conflicts.length,0);
assert.equal(replacementPreview('bahv',[base,{...base,verification:'Tidak Direkomendasikan'}],{}).canSubmit,false);
assert.equal(replacementPreview('bahv',[{...base,nik:'123'}],{}).canSubmit,false);
assert.equal(replacementPreview('bahv',[{...base,ba:''}],{}).canSubmit,true);
assert.equal(mergeSources({pb:[base]})[0].rabCandidate,false);
assert.equal(mergeSources({bahv:[base],pb:[base]})[0].rabCandidate,true);
console.log('Import mapping, refresh, conflict preservation, validation and BA-HV scope passed.');
